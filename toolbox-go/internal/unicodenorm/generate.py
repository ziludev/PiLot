#!/usr/bin/env python3
"""Regenerate tables_gen.go from the Unicode database that ships with Python.

Keeping the tables in the repository is what lets the Go side normalize text without a dependency.
Run this after a Python upgrade changes `unicodedata.unidata_version`; the tests compare a sample of
the tables against expectations, and `go test` fails if a table cannot be parsed.

The generator refuses to run when its Unicode version differs from node's, and gofmt owns the
alignment of the literal, so the whole regeneration is:

    python3 generate.py > tables_gen.go && gofmt -w tables_gen.go
"""

import sys
import shutil
import subprocess
import unicodedata

MAX = 0x110000
HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def raw(chars: str) -> str:
    """A Go raw string holding `chars`; the data has no backquotes or carriage returns."""
    for ch in chars:
        if ch == "`" or ch == "\r":
            raise SystemExit("table data contains a character a raw string cannot hold: %r" % ch)
    return "`" + chars + "`"


def records(pairs):
    """Split the table: a raw string cannot hold a backquote, and three records contain one."""
    plain, escaped = [], []
    for source, target in pairs:
        if "`" in target:
            escaped.append('%s|%s\\n' % (source.replace("\\", "\\\\").replace('"', '\\"').replace("`", "\\x60"), target.replace("\\", "\\\\").replace('"', '\\"').replace("`", "\\x60")))
        else:
            plain.append("%s|%s" % (source, target))
    return "\n".join(plain), "".join(escaped)


def check_node_version(version: str) -> None:
    """Fail when this Python's Unicode version differs from the runtime the toolbox must match."""
    node = shutil.which("node")
    if node is None:
        return
    reported = subprocess.run(
        [node, "-p", "process.versions.unicode"], capture_output=True, text=True, check=True
    ).stdout.strip()
    # Node reports the major and minor version only ("17.0"), Python the full one ("17.0.0").
    short = ".".join(version.split(".")[:2])
    if reported and reported != short:
        raise SystemExit(
            "unicodedata is Unicode %s but node reports Unicode %s; regenerate with a Python whose "
            "Unicode version matches node" % (version, reported)
        )


def main() -> None:
    canonical = {}
    compatibility = {}
    by_class = {}
    composites = []

    for cp in range(MAX):
        if HANGUL_FIRST <= cp <= HANGUL_LAST:
            continue
        ch = chr(cp)
        nfd = unicodedata.normalize("NFD", ch)
        if nfd != ch:
            canonical[cp] = nfd
        nfkd = unicodedata.normalize("NFKD", ch)
        if nfkd != ch:
            compatibility[cp] = nfkd
        klass = unicodedata.combining(ch)
        if klass:
            by_class.setdefault(klass, []).append(ch)
        decomposition = unicodedata.decomposition(ch)
        if decomposition and not decomposition.startswith("<"):
            parts = decomposition.split()
            if len(parts) == 2 and unicodedata.normalize("NFC", ch) == ch:
                composites.append((int(parts[0], 16), int(parts[1], 16), cp))

    canonical_plain, canonical_extra = records((chr(cp), canonical[cp]) for cp in sorted(canonical))
    compatibility_plain, compatibility_extra = records((chr(cp), compatibility[cp]) for cp in sorted(compatibility))
    check_node_version(unicodedata.unidata_version)
    out = [
        "// Code generated by generate.py from Unicode %s. DO NOT EDIT." % unicodedata.unidata_version,
        "",
        "package unicodenorm",
        "",
        "// canonicalDecomposition is one \"source|decomposition\" record per line: the full NFD form",
        "// of every code point whose NFD differs, Hangul syllables excepted (they decompose by",
        "// arithmetic, see decomposeHangul).",
        "const canonicalDecomposition = " + raw(canonical_plain),
        "",
        "// canonicalDecompositionExtra carries the records a raw string cannot hold.",
        "const canonicalDecompositionExtra = " + '"' + canonical_extra + '"',
        "",
        "// compatibilityDecomposition is the same for NFKD.",
        "const compatibilityDecomposition = " + raw(compatibility_plain),
        "",
        "// compatibilityDecompositionExtra is the same for the records with a backquote.",
        "const compatibilityDecompositionExtra = " + '"' + compatibility_extra + '"',
        "",
        "// combiningByClass holds the non-starters grouped by canonical combining class, which is what",
        "// canonical ordering and composition blocking need.",
        "var combiningByClass = map[uint8]string{",
    ]
    for klass in sorted(by_class):
        out.append("\t%d: %s," % (klass, raw("".join(by_class[klass]))))
    out += [
        "}",
        "",
        "// primaryComposites is one \"first,second,composed\" triple per line: the pairs NFC composes.",
        "const primaryComposites = " + raw("\n".join(
            "%s%s%s" % (chr(first), chr(second), chr(composed)) for first, second, composed in composites
        )),
        "",
    ]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
